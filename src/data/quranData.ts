export function getSurahByNumber(num: number): SurahInfo | undefined {
  return QURAN_SURAHS.find(s => s.number === num);
}

export function getSurahByName(name: string): SurahInfo | undefined {
  return QURAN_SURAHS.find(s => s.name === name);
}

export function getAyahCount(surahNumber: number): number {
  const surah = getSurahByNumber(surahNumber);
  return surah ? surah.versesCount : 1;
}
